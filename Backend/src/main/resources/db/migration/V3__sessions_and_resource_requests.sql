CREATE TABLE infrastructure_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id),
    environment VARCHAR(20) NOT NULL,
    resource_type VARCHAR(30) NOT NULL,
    resource_size VARCHAR(20) NOT NULL,
    justification VARCHAR(2000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    requested_by_id BIGINT NOT NULL REFERENCES users(id),
    reviewed_by_id BIGINT REFERENCES users(id),
    decision_note VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_request_status CHECK (status IN ('PENDING','APPROVED','REJECTED')),
    CONSTRAINT ck_request_env CHECK (environment IN ('DEV','STAGING','PRODUCTION'))
);
CREATE INDEX ix_requests_status ON infrastructure_requests(status);

CREATE TABLE notification_reads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event_id BIGINT NOT NULL REFERENCES audit_events(id),
    CONSTRAINT uq_notification_read UNIQUE(user_id,event_id)
);
